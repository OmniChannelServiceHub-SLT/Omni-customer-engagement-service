const Ajv = require('ajv-draft-04');
const addFormats = require('ajv-formats');

const specification = require(
  './TMF621-TroubleTicket-v4.0.0.swagger.json'
);

const ajv = new Ajv({
  allErrors: true,
  strict: false,
});

addFormats(ajv);

const validate = ajv.compile({
  $schema: 'http://json-schema.org/draft-04/schema#',
  definitions: specification.definitions,
  $ref: '#/definitions/TroubleTicket_Create',
});

function validateCreateRequest(body) {
  if (!validate(body)) {
    const err = new Error(
      ajv.errorsText(validate.errors, { separator: '; ' })
    );

    err.status = 400;
    err.code = 'INVALID_REQUEST';
    throw err;
  }

  for (const field of ['description', 'severity', 'ticketType']) {
    if (!body[field].trim()) {
      const err = new Error(`${field} must not be empty`);
      err.status = 400;
      err.code = 'INVALID_REQUEST';
      throw err;
    }
  }

  const generatedFields = [
    'id',
    'href',
    'creationDate',
    'lastUpdate',
    'statusChangeDate',
    'statusChange',
  ];

  for (const field of generatedFields) {
    if (Object.prototype.hasOwnProperty.call(body, field)) {
      const err = new Error(`${field} is generated by the server`);
      err.status = 400;
      err.code = 'INVALID_REQUEST';
      throw err;
    }
  }

  const allowed = new Set(
    Object.keys(
      specification.definitions.TroubleTicket_Create.properties
    )
  );

  for (const field of Object.keys(body)) {
    if (!allowed.has(field)) {
      const err = new Error(`Unsupported field: ${field}`);
      err.status = 400;
      err.code = 'INVALID_REQUEST';
      throw err;
    }
  }
}

module.exports = { validateCreateRequest };