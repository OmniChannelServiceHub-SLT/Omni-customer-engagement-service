module.exports = function gatewayIdentity(req, res, next) {
  const requireGateway =
    String(process.env.REQUIRE_GATEWAY || 'false').toLowerCase() === 'true';

  const expectedGateway =
    process.env.EXPECTED_GATEWAY_HEADER || 'omnichannel-api-gateway';

  if (requireGateway && req.headers['x-gateway'] !== expectedGateway) {
    return res.status(401).json({
      error: {
        code: 'GATEWAY_REQUIRED',
        message: 'This service must be accessed through the API Gateway.',
        correlationId: req.correlationId || null,
      },
    });
  }

  // JWT is verified by the API Gateway.
  // The service consumes only the trusted identity headers generated by Gateway.
  req.identity = {
    userId: req.headers['x-user-id'] || null,
    roles: String(req.headers['x-user-roles'] || '')
      .split(',')
      .map((role) => role.trim())
      .filter(Boolean),
    scope: req.headers['x-user-scope'] || null,
  };

  next();
};
